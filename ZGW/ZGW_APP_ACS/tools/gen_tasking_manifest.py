#!/usr/bin/env python3
"""Generate tasking_sources.mk and tasking_includes.opt for ZGW_APP_ACS.

Source of truth: the TASKING build that AURIX Development Studio generated for
ZGW_APP ("TriCore Debug (TASKING)": subdir.mk files and the include .opt file).
Every source is emitted with the exact cctc/astc option variant ADS used for it,
so the ACS-driven build compiles each file with the same options as the ADS build.

Usage (from anywhere):
    python gen_tasking_manifest.py [ADS_BUILD_DIR]

ADS_BUILD_DIR defaults to ../../ZGW_APP/TriCore Debug (TASKING) relative to this file.
Re-run after the ADS source set or per-file options change.
"""
import collections
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
ads = sys.argv[1] if len(sys.argv) > 1 else os.path.join(PROJ, '..', 'ZGW_APP', 'TriCore Debug (TASKING)')
ads = os.path.abspath(ads)

RULE = re.compile(
    r'^"(?P<out>[^"]+\.(?:src|o))":"(?P<in>[^"]+)"[^\n]*\n\t(?P<tool>cctc|astc)\s(?P<args>[^\n]*)$',
    re.M)


def norm_cc(args):
    args = re.sub(r'"-f[^"]*"', '', args)          # machine-specific include .opt, replaced by ours
    args = re.sub(r'--dep-file="\$\*\.d"', '', args)  # re-added by the makefile
    args = re.sub(r'\s*-o\s+"\$@"\s+"\$<"\s*$', '', args)
    return re.sub(r'\s+', ' ', args).strip()


def norm_as(args):
    args = re.sub(r'\s*-o\s+"\$@"\s+"\$<"\s*$', '', args)
    return re.sub(r'\s+', ' ', args).strip()


entries = {}  # rel (without ext) -> dict(src=, cc=, as=)
for mk in sorted(glob.glob(os.path.join(ads, '**', 'subdir.mk'), recursive=True)):
    text = open(mk, encoding='utf8', errors='replace').read()
    for m in RULE.finditer(text):
        out, inp, tool, args = m.group('out'), m.group('in'), m.group('tool'), m.group('args')
        base = out.rsplit('.', 1)[0]
        e = entries.setdefault(base, {})
        if tool == 'cctc':
            if not inp.startswith('../'):
                raise SystemExit('unexpected source path: ' + inp)
            e['src'] = inp[3:]
            e['cc'] = norm_cc(args)
        else:
            e['as'] = norm_as(args)

missing = [b for b, e in entries.items() if not {'src', 'cc', 'as'} <= e.keys()]
if missing:
    raise SystemExit('incomplete rules for: %s' % missing[:5])

cc_variants = collections.Counter(e['cc'] for e in entries.values())
as_variants = collections.Counter(e['as'] for e in entries.values())
cc_ids = {v: i for i, (v, _) in enumerate(cc_variants.most_common())}
as_ids = {v: i for i, (v, _) in enumerate(as_variants.most_common())}

out = ['# Generated by tools/gen_tasking_manifest.py from the ADS TASKING build. Do not edit.',
       '# One entry per source: path relative to ZGW_APP, compiler (cctc) and assembler (astc) option variant.', '']
for v, i in cc_ids.items():
    out.append('CC_V%d := %s' % (i, v))
for v, i in as_ids.items():
    out.append('AS_V%d := %s' % (i, v))
out.append('')
out.append('SRCS := \\')
for b in sorted(entries):
    out.append('  %s \\' % entries[b]['src'])
out.append('')
for b in sorted(entries):
    e = entries[b]
    rel = e['src'].rsplit('.', 1)[0]
    if rel != b:
        raise SystemExit('output/source stem mismatch: %s vs %s' % (b, rel))
    out.append('CC_VAR_%s := CC_V%d' % (rel, cc_ids[e['cc']]))
    out.append('AS_VAR_%s := AS_V%d' % (rel, as_ids[e['as']]))
open(os.path.join(PROJ, 'tasking_sources.mk'), 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')

# Include paths: ADS wrote absolute paths of another checkout; rewrite relative to ZGW_APP_ACS (make runs there).
opt = open(glob.glob(os.path.join(ads, 'TASKING_C_C___Compiler-Include_paths__-I_.opt'))[0], encoding='utf8').read()
paths = re.findall(r'-I"([^"]+)"', opt)
roots = [p for p in paths if p.lower().endswith('zgw_app')]
if len(roots) != 1:
    raise SystemExit('cannot locate ZGW_APP root in include list')
root = roots[0].replace('\\\\', '\\')
lines = []
for p in paths:
    p = p.replace('\\\\', '\\')
    if not p.lower().startswith(root.lower()):
        lines.append('-I"%s"' % p.replace('\\', '/'))  # external (toolchain) path, keep
        continue
    rel = p[len(root):].lstrip('\\').replace('\\', '/')
    lines.append('-I"../ZGW_APP%s"' % ('/' + rel if rel else ''))
open(os.path.join(PROJ, 'tasking_includes.opt'), 'w', encoding='utf8', newline='\n').write('\n'.join(lines) + '\n')
print('%d sources, %d cc variants, %d as variants, %d include paths' % (len(entries), len(cc_ids), len(as_ids), len(lines)))
